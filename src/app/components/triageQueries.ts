// What each alert's analysis checked, what came back, and the KQL it ran.
// Modelled on the Resolve output: query names, sources, row counts, skipped
// checks. Every alert mixes states on purpose so all five read differently:
// completed with rows, completed with none, skipped, failed, unavailable.
